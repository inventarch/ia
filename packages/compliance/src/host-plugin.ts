const HOOK = [
  '// Generated by ia host --user; do not edit. docs/specs/host-plugin-distribution/README.md §8.',
  "import { spawn, spawnSync } from 'node:child_process';",
  "import { accessSync, constants, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';",
  "import { homedir } from 'node:os';",
  "import { delimiter, dirname, isAbsolute, join, parse } from 'node:path';",
  "import { fileURLToPath } from 'node:url';",
  'const here = dirname(fileURLToPath(import.meta.url));',
  '// Only fully qualified PATH entries count. An empty or relative entry names the project directory, which the',
  '// repository controls, and on Windows a rooted entry without a drive or share depends on the current drive (LKI-41).',
  'function qualified(path) {',
  "  return isAbsolute(path) && (process.platform !== 'win32' || parse(path).root.length > 1);",
  '}',
  '// PATH entries that count: qualified ones only. Windows allows an entry in quotes and no quote in a file name, so the',
  '// quotes go there; on POSIX a quote is part of a directory name and every entry stays as written.',
  'function pathEntries() {',
  "  const entries = (process.env.PATH || '').split(delimiter);",
  "  return (process.platform === 'win32' ? entries.map((entry) => entry.replace(/\"/g, '')) : entries).filter(qualified);",
  '}',
  '// The hook looks ia up itself on every platform: cmd.exe reports an unknown command only as a localized message',
  '// with exit 1, the status a real ia doctor failure can have, so no shell is ever asked to fail (LKI-40). Only the four',
  '// types cmd.exe starts as programs count; the PATHEXT script types would start through Windows Script Host.',
  'function findOnPath(name) {',
  "  const windows = process.platform === 'win32';",
  "  const names = windows ? ['.com', '.exe', '.bat', '.cmd'].map((extension) => name + extension) : [name];",
  '  for (const dir of pathEntries()) {',
  '    try {',
  '      if (!statSync(dir).isDirectory()) continue;',
  '    } catch { continue; /* a missing directory costs one check, not one per name */ }',
  '    for (const candidate of names) {',
  '      const file = join(dir, candidate);',
  "      if (windows && file.includes('%')) continue; // cmd.exe would expand %NAME% even inside quotes",
  '      try {',
  '        if (!statSync(file).isFile()) continue;',
  '        if (!windows) accessSync(file, constants.X_OK);',
  '        return file;',
  '      } catch { /* absent or not executable: keep looking, as the shell would */ }',
  '    }',
  '  }',
  '  return null;',
  '}',
  '// cmd.exe by absolute path, since a bare cmd.exe would itself be looked up in the current directory first, and never',
  "// ComSpec: Node gives a shell cmd.exe's switches only when its path matches cmd.exe with backslashes, so it would pass",
  '// -c to another program or to cmd.exe spelled with forward slashes. The hook passes the switches itself (LKI-41).',
  'function windowsShell() {',
  "  const root = process.env.SystemRoot || '';",
  "  return join(qualified(root) ? root : 'C:/Windows', 'System32', 'cmd.exe');",
  '}',
  "// cmd.exe's switches, passed verbatim: /d skips AutoRun commands, /v:off stops a delayed expansion that the registry",
  '// turns on from reading a ! in the path, and /s /c runs the line inside the outer quotes as written.',
  'function windowsArgs(file, args) {',
  "  return ['/d', '/v:off', '/s', '/c', '\"\"' + file + '\" ' + args.join(' ') + '\"'];",
  '}',
  '// Every child the hook starts (doctor, an ia launcher, the update refresh) sees only the qualified entries and, on',
  "// Windows, no implicit current directory, so its own lookups (npm's ia.cmd runs node by name; doctor runs git) cannot",
  '// reach the project either (LKI-41).',
  'function childEnv() {',
  '  const env = {};',
  "  for (const [key, value] of Object.entries(process.env)) if (key.toUpperCase() !== 'PATH') env[key] = value;",
  '  const entries = pathEntries();',
  '  // POSIX reads an empty PATH as the current directory, so a PATH with no qualified entry becomes the system one.',
  "  env.PATH = entries.length > 0 || process.platform === 'win32' ? entries.join(delimiter) : '/usr/bin:/bin';",
  "  if (process.platform === 'win32') env.NoDefaultCurrentDirectoryInExePath = '1';",
  '  return env;',
  '}',
  'function main() {',
  '  try {',
  "    const meta = JSON.parse(readFileSync(join(here, '..', 'ia-plugin.json'), 'utf8'));",
  "    const notFound = { context: 'InventArch: the ia CLI was not found. ' + meta.install + ' Do not search the filesystem for IA tooling.', notice: 'IA: the ia CLI was not found; see the session context.' };",
  '    const project = process.env.CLAUDE_PROJECT_DIR || process.cwd();',
  "    const args = ['doctor', '--json', '--host', 'claude'];",
  "    const options = { cwd: project, encoding: 'utf8', timeout: 5000, windowsHide: true };",
  '    const hasEntry = existsSync(meta.entry);',
  "    const found = hasEntry ? null : findOnPath('ia');",
  '    if (!hasEntry && found === null) return notFound;',
  '    // The file found runs by its absolute path, on Windows through cmd.exe (a .cmd launcher needs it), so no step of',
  '    // the launch searches the project directory (LKI-41). Not found is decided here, before anything starts.',
  '    const run = hasEntry',
  '      ? spawnSync(process.execPath, [meta.entry].concat(args), Object.assign({}, options, { env: childEnv() }))',
  "      : process.platform === 'win32'",
  '        ? spawnSync(windowsShell(), windowsArgs(found, args), Object.assign({}, options, { env: childEnv(), windowsVerbatimArguments: true }))',
  '        : spawnSync(found, args, Object.assign({}, options, { env: childEnv() }));',
  "    if (run.error && run.error.code === 'ETIMEDOUT') return { context: 'IA status unavailable: ia doctor timed out.', notice: null };",
  '    if (!run.stdout) {',
  '      const outcome = run.status ?? run.signal;',
  "      if (outcome === null || outcome === undefined) return { context: 'IA status unavailable: ia doctor did not run.', notice: null };",
  "      return { context: 'IA status unavailable: ia doctor exited ' + outcome + '.', notice: null };",
  '    }',
  '    const session = JSON.parse(run.stdout).session;',
  "    if (!session) return { context: 'IA status unavailable: this ia does not report session state. ' + meta.install, notice: null };",
  '    let notice = session.notice;',
  "    if (notice && session.nudge === 'update' && process.env.CLAUDE_PLUGIN_DATA) {",
  '      try {',
  "        const file = join(process.env.CLAUDE_PLUGIN_DATA, 'nudged-on'), today = new Date().toLocaleDateString('en-CA');",
  "        if (existsSync(file) && readFileSync(file, 'utf8') === today) notice = null;",
  '        else { mkdirSync(process.env.CLAUDE_PLUGIN_DATA, { recursive: true }); writeFileSync(file, today); }',
  '      } catch { /* the nudge file is best-effort; never let it block the briefing */ }',
  '    }',
  '    if (Array.isArray(session.refresh) && session.refresh.length > 0) {',
  '      try {',
  "        const child = spawn(session.refresh[0], session.refresh.slice(1), { cwd: homedir(), env: childEnv(), detached: true, stdio: 'ignore', windowsHide: true });",
  "        child.on('error', () => {});",
  '        child.unref();',
  '      } catch { /* the refresh is best-effort; never let it block the briefing */ }',
  '    }',
  "    return { context: session.context.join('\\n'), notice };",
  '  } catch (error) {',
  "    return { context: 'IA status unavailable: ' + (error && error.code ? error.code : 'unexpected error') + '.', notice: null };",
  '  }',
  '}',
  'const result = main();',
  "process.stdout.write(JSON.stringify(Object.assign(result.notice ? { systemMessage: result.notice } : {}, { hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: result.context } })) + '\\n');",
  'process.exitCode = 0;',
  '',
].join('\n');

export function renderClaudePlugin(input: ClaudePluginInput): readonly PluginFile[] {
  const files: PluginFile[] = [
    {
      path: '.claude-plugin/marketplace.json',
      text: json({
        name: CLAUDE_MARKETPLACE,
        owner: { name: 'InventArch' },
        description:
          'InventArch: session state from ia doctor, and init, doctor and authoring skills for .ia workspaces.',
        plugins: [
          {
            name: CLAUDE_PLUGIN,
            source: './plugins/ia',
            description: 'InventArch front door: session state from ia doctor, and init, doctor and authoring skills.',
          },
        ],
      }),
    },
    {
      path: 'plugins/ia/.claude-plugin/plugin.json',
      text: json({
        name: CLAUDE_PLUGIN,
        version: input.version,
        description:
          'InventArch front door. Reports ia doctor state at session start and offers init, doctor and authoring skills. No engine and no MCP server; workspace registration is ia host claude.',
        author: { name: 'InventArch' },
      }),
    },
    { path: 'plugins/ia/agents/ia-author.md', text: AUTHOR },
    {
      path: 'plugins/ia/hooks/hooks.json',
      text: json({
        hooks: {
          SessionStart: [
            {
              matcher: 'startup|clear',
              hooks: [
                { type: 'command', command: 'node "${CLAUDE_PLUGIN_ROOT}/hooks/session-start.mjs"', timeout: 10 },
              ],
            },
          ],
        },
      }),
    },
    { path: 'plugins/ia/hooks/session-start.mjs', text: HOOK },
    {
      path: 'plugins/ia/ia-plugin.json',
      text: json({
        format: 'ia.claude-plugin.v1',
        cli: input.cliVersion,
        channel: input.channel,
        entry: input.entry,
        install: input.install,
      }),
    },
    { path: 'plugins/ia/skills/authoring/SKILL.md', text: AUTHORING },
    { path: 'plugins/ia/skills/doctor/SKILL.md', text: DOCTOR },
    { path: 'plugins/ia/skills/init/SKILL.md', text: INIT },
  ];
  return Object.freeze(files.map((file) => Object.freeze(file)));
}
