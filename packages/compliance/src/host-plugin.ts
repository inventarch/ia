export const CLAUDE_PLUGIN = 'ia';
export const CLAUDE_MARKETPLACE = 'inventarch';
export const PLUGIN_MARKER = '<!-- Generated by ia host --user; do not edit. -->';
export interface ClaudePluginInput {
  /** plugin.json version: `<cli version>+<first 12 hex of the payload digest>`. */
  readonly version: string;
  readonly cliVersion: string;
  readonly channel: 'checkout' | 'npm' | 'unknown';
  /** Absolute path of the CLI entry that rendered this plugin; the hook runs it first (§8.1, amended). */
  readonly entry: string;
  /** §5's update instruction, which the hook repeats when `ia` cannot be found. */
  readonly install: string;
}
export interface PluginFile {
  readonly path: string;
  readonly text: string;
}
