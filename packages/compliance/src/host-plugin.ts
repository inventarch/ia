/**
 * The hook's command in hooks.json, in shell form (no `args`) like the earlier command, so it needs no host that
 * supports exec form. Claude Code's hooks reference passes such a command to `sh -c` on macOS and
 * Linux, to Git Bash on Windows, or to PowerShell when Git Bash isn't installed. On macOS and Linux it names the
 * recorded Node by absolute path in double quotes, so sh starts that file and looks no `node` up. On Windows it stays
 * the earlier `node "…"`: PowerShell reads a line that opens with a quoted string as an expression, not a command, so a
 * quoted path that Git Bash would run does not run there. `node` is still looked up on PATH on Windows.
 */
const HOOK_SCRIPT = '"${CLAUDE_PLUGIN_ROOT}/hooks/session-start.mjs"';
function hookCommand(node: string, platform: NodeJS.Platform): string {
  if (platform === 'win32') return `node ${HOOK_SCRIPT}`;
  // Absolute, and without `${`, which the host would substitute.
  if (!posix.isAbsolute(node) || node.includes('$' + '{'))
    throw new Error(
      `renderClaudePlugin: node must be the fully qualified path of a Node executable, without "$` +
        `{"; got ${JSON.stringify(node)}`,
    );
  // Inside double quotes sh reads $, ` and ", and a backslash before another backslash or the closing quote; cmd.exe
  // would expand % and !; a control character can end the line or hide in it.
  if (/["$`%!\p{Cc}]|\\\\|\\$/u.test(node))
    throw new Error(
      `renderClaudePlugin: node must read the same inside double quotes in sh, so it holds no ", $, \`, %, !, control character, doubled backslash or final backslash; got ${JSON.stringify(node)}`,
    );
  return `"${node}" ${HOOK_SCRIPT}`;
}

/** `platform` is the machine the plugin is installed on: `ia host claude --user --apply` renders it there. */
export function renderClaudePlugin(
  input: ClaudePluginInput,
  platform: NodeJS.Platform = process.platform,
): readonly PluginFile[] {
  const hook = { type: 'command', command: hookCommand(input.node, platform), timeout: 10 };
  const files: PluginFile[] = [
    {
      path: '.claude-plugin/marketplace.json',
      text: json({
        name: CLAUDE_MARKETPLACE,
        owner: { name: 'InventArch' },
        description:
          'InventArch: session state from ia doctor, and init, doctor and authoring skills for .ia workspaces.',
        plugins: [
          {
            name: CLAUDE_PLUGIN,
            source: './plugins/ia',
            description: 'InventArch front door: session state from ia doctor, and init, doctor and authoring skills.',
          },
        ],
      }),
    },
    {
      path: 'plugins/ia/.claude-plugin/plugin.json',
      text: json({
        name: CLAUDE_PLUGIN,
        version: input.version,
        description:
          'InventArch front door. Reports ia doctor state at session start and offers init, doctor and authoring skills. No engine and no MCP server; workspace registration is ia host claude.',
        author: { name: 'InventArch' },
      }),
    },
    { path: 'plugins/ia/agents/ia-author.md', text: AUTHOR },
    {
      path: 'plugins/ia/hooks/hooks.json',
      text: json({ hooks: { SessionStart: [{ matcher: 'startup|clear', hooks: [hook] }] } }),
    },
    { path: 'plugins/ia/hooks/session-start.mjs', text: HOOK },
    {
      path: 'plugins/ia/ia-plugin.json',
      text: json({
        format: 'ia.claude-plugin.v1',
        cli: input.cliVersion,
        channel: input.channel,
        entry: input.entry,
        install: input.install,
      }),
    },
    { path: 'plugins/ia/skills/authoring/SKILL.md', text: AUTHORING },
    { path: 'plugins/ia/skills/doctor/SKILL.md', text: DOCTOR },
    { path: 'plugins/ia/skills/init/SKILL.md', text: INIT },
  ];
  return Object.freeze(files.map((file) => Object.freeze(file)));
}
