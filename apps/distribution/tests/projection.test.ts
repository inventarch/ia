const stateFiles = (root: string): Record<string, string> =>
  (JSON.parse(read(root, STATE)) as { files: Record<string, string> }).files;

it('owns the agents and skills generation writes in the projection state, and removes each owned one no render writes', () => {
  const root = temp();
  put(root, '.claude/agents/mine.md', 'my own agent\n');
  const first = planProjection({ root, host: 'claude', artifacts: generated(), marker: MARK });
  expect(first.actions).toEqual([
    { path: '.claude/agents/mine.md', action: 'foreign' },
    { path: AGENT, action: 'create' },
    { path: '.claude/rules/ia-workspace.md', action: 'create' },
    { path: '.claude/skills/ia-authoring/SKILL.md', action: 'create' },
    { path: SKILL, action: 'create' },
  ]);
  applyProjection(first);
  expect(Object.keys(stateFiles(root)).sort()).toEqual([
    AGENT,
    '.claude/rules/ia-workspace.md',
    '.claude/skills/ia-authoring/SKILL.md',
    SKILL,
  ]);
  expect(observeProjection({ root, host: 'claude', artifacts: generated(), marker: MARK })).toEqual([]);
  // The same render again changes nothing; another updates each generated file in place.
  expect(
    planProjection({ root, host: 'claude', artifacts: generated(), marker: MARK }).actions.filter(
      (row) => row.action !== 'unchanged' && row.action !== 'foreign',
    ),
  ).toEqual([]);
  applyProjection(planProjection({ root, host: 'claude', artifacts: generated(' v2'), marker: MARK }));
  // The profile and the playbook are gone from the records: both owned files are removed, the user's agent is not.
  const removal = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  expect(removal.actions.filter((row) => row.action === 'remove' || row.action === 'foreign')).toEqual([
    { path: '.claude/agents/mine.md', action: 'foreign' },
    { path: AGENT, action: 'remove' },
    { path: SKILL, action: 'remove' },
  ]);
  applyProjection(removal);
  for (const path of [AGENT, SKILL]) expect(existsSync(resolve(root, path)), path).toBe(false);
  expect(read(root, '.claude/agents/mine.md')).toBe('my own agent\n');
  expect(Object.keys(stateFiles(root)).sort()).toEqual([
    '.claude/rules/ia-workspace.md',
    '.claude/skills/ia-authoring/SKILL.md',
  ]);
});

