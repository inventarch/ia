/** The marker the position packet's files carry (runtime PACKET_MARKER), which the CLI passes as the plan's marker. */
const MARK = '<!-- Generated by ia project; edit the cited native records. -->';
/** B9: the two 1.x markers, compliance's WORKSPACE_PROJECTION_MARKER (ia host) and PROJECTION_MARKER (this repository). */
const HOST_MARK = '<!-- Generated by ia host; edit the cited native records. -->',
  REPO_MARK = '<!-- Generated by tools/projections/generate.ts; edit the cited native records. -->';
const STATE = '.ia/distributions/hosts/claude-projection.json',
  STEWARD = '.claude/agents/demo-steward.md';
const made: string[] = [];
const temp = () => {
  const p = mkdtempSync(join(tmpdir(), 'ia-projection-'));
  made.push(p);
  return p;
};
afterEach(() => {
  for (const p of made.splice(0)) rmSync(p, { recursive: true, force: true });
});
const put = (root: string, path: string, text: string) => {
  mkdirSync(dirname(resolve(root, path)), { recursive: true });
  writeFileSync(resolve(root, path), text);
};
const read = (root: string, path: string) => readFileSync(resolve(root, path), 'utf8');
const artifacts = (extra = '') => [
  { path: '.claude/rules/ia-workspace.md', text: `${MARK}\n\n# IA position packet${extra}\n` },
  { path: '.claude/skills/ia-authoring/SKILL.md', text: `---\nname: ia-authoring\n---\n\n${MARK}\n` },
];
/** A second/third render of the same set: every path's bytes change, so hand-edit tolerance is genuinely exercised. */
const bump = (list: ReturnType<typeof artifacts>, tag: string) =>
  list.map((a) => ({ ...a, text: `${a.text}${tag}\n` }));
/** A 1.x claude projection as `ia host` wrote it: the files, and a state listing each with its digest. */
function legacy(root: string, files: Readonly<Record<string, string>>): void {
  for (const [path, text] of Object.entries(files)) put(root, path, text);
  put(
    root,
    STATE,
    json({
      format: 'ia.host-projection-state.v1',
      host: 'claude',
      files: Object.fromEntries(Object.entries(files).map(([path, text]) => [path, sha256(text)])),
    }),
  );
}
const steward = (marker: string) => `---\nname: demo-steward\n---\n\n${marker}\n\nSource revision: x\n`;
const where = (run: () => unknown): { code?: string; path?: string; message?: string } => {
  try {
    run();
  } catch (error) {
    return error as { code?: string; path?: string; message?: string };
  }
  return {};
};

it('creates, updates, removes owned stale files and leaves CLAUDE.md alone', () => {
  const root = temp();
  put(root, 'CLAUDE.md', 'mine\n');
  applyProjection(planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }));
  expect(observeProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual([]);
  const next = artifacts(' v2').slice(0, 1),
    plan = planProjection({ root, host: 'claude', artifacts: next, marker: MARK });
  expect(plan.actions).toEqual([
    { path: '.claude/rules/ia-workspace.md', action: 'update' },
    { path: '.claude/skills/ia-authoring/SKILL.md', action: 'remove' },
  ]);
  applyProjection(plan);
  expect(existsSync(resolve(root, '.claude/skills/ia-authoring/SKILL.md'))).toBe(false);
  expect(read(root, 'CLAUDE.md')).toBe('mine\n');
});
it('refuses an unmanaged file, a hand edit and any path outside the allowlist, a steward file included', () => {
  const root = temp();
  put(root, '.claude/rules/ia-workspace.md', 'user file\n');
  expect(() => planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).toThrow(
    /unmanaged file at a managed path: \.claude\/rules\/ia-workspace\.md/,
  );
  expect(read(root, '.claude/rules/ia-workspace.md')).toBe('user file\n');
  const other = temp();
  applyProjection(planProjection({ root: other, host: 'claude', artifacts: artifacts(), marker: MARK }));
  put(other, '.claude/rules/ia-workspace.md', `${MARK}\n\nedited\n`);
  expect(observeProjection({ root: other, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual([
    { path: '.claude/rules/ia-workspace.md', drift: 'changed' },
  ]);
  expect(() => planProjection({ root: other, host: 'claude', artifacts: artifacts(), marker: MARK })).toThrow(
    /edited by hand/,
  );
  // B9: no projection writes a steward file any more, and CLAUDE.md is the repository's, never a consumer's.
  for (const path of ['CLAUDE.md', STEWARD])
    expect(
      where(() => planProjection({ root: temp(), host: 'claude', artifacts: [{ path, text: MARK }], marker: MARK })),
      path,
    ).toMatchObject({ code: 'IA-DIST-PATH-UNSAFE', message: expect.stringContaining('outside the claude allowlist') });
  expect(PROJECTION_PATHS).toEqual({
    claude: ['.claude/rules/ia-workspace.md', '.claude/skills/ia-authoring/SKILL.md'],
    codex: ['AGENTS.md', '.agents/skills/ia-authoring/SKILL.md'],
  });
});
