it('refuses a tampered ownership state naming an unallowlisted path or a malformed hash', () => {
  const tampered = (files: Record<string, string>, host: 'claude' | 'codex' = 'claude') => {
    const root = temp();
    put(
      root,
      `.ia/distributions/hosts/${host}-projection.json`,
      json({ format: 'ia.host-projection-state.v1', host, files }),
    );
    return root;
  };
  for (const [root, host] of [
    [tampered({ 'CLAUDE.md': 'a'.repeat(64) }), 'claude'],
    [tampered({ '.claude/rules/ia-workspace.md': 'not-a-sha256' }), 'claude'],
    [tampered({ '../outside.md': sha256('x') }), 'claude'],
    // A steward file is a claude path; a codex state never listed one.
    [tampered({ [STEWARD]: sha256('x') }, 'codex'), 'codex'],
    [tampered({ '.claude/agents/Upper.md': sha256('x') }), 'claude'],
  ] as const) {
    expect(() => planProjection({ root, host, artifacts: [], marker: MARK })).toThrow(
      /Invalid projection ownership state/,
    );
    expect(() => observeProjection({ root, host, artifacts: null, marker: MARK })).toThrow(
      /Invalid projection ownership state/,
    );
  }
});

// --- B9: a 1.x projection upgrades in place. ---
it("upgrades a 1.x claude projection: legacy-marked owned files are replaced and the state's steward files deleted", () => {
  const root = temp(),
    rules = `${HOST_MARK}\n\n# IA workspace\n`,
    skill = `---\nname: ia-authoring\n---\n\n${HOST_MARK}\n`;
  legacy(root, {
    '.claude/rules/ia-workspace.md': rules,
    '.claude/skills/ia-authoring/SKILL.md': skill,
    [STEWARD]: steward(HOST_MARK),
    // This repository's own 1.x marker is owned too.
    '.claude/agents/repo-steward.md': steward(REPO_MARK),
  });
  const plan = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  expect(plan.actions).toEqual([
    { path: STEWARD, action: 'remove' },
    { path: '.claude/agents/repo-steward.md', action: 'remove' },
    { path: '.claude/rules/ia-workspace.md', action: 'update' },
    { path: '.claude/skills/ia-authoring/SKILL.md', action: 'update' },
  ]);
  expect(applyProjection(plan)).toEqual({ status: 'projected', written: 2, removed: 2 });
  expect(existsSync(resolve(root, STEWARD))).toBe(false);
  expect(existsSync(resolve(root, '.claude/agents/repo-steward.md'))).toBe(false);
  for (const artifact of artifacts()) expect(read(root, artifact.path)).toBe(artifact.text);
  // The state format is unchanged; it now lists only what the packet renders.
  expect(JSON.parse(read(root, STATE))).toEqual({
    format: 'ia.host-projection-state.v1',
    host: 'claude',
    files: Object.fromEntries(artifacts().map((artifact) => [artifact.path, sha256(artifact.text)])),
  });
  expect(observeProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual([]);
  // A codex projection's legacy-marked AGENTS.md is replaced the same way.
  const codex = temp(),
    agents = { path: 'AGENTS.md', text: `${MARK}\n\n# IA position packet\n` };
  put(codex, 'AGENTS.md', `${HOST_MARK}\n\n# IA workspace\n`);
  put(
    codex,
    '.ia/distributions/hosts/codex-projection.json',
    json({
      format: 'ia.host-projection-state.v1',
      host: 'codex',
      files: { 'AGENTS.md': sha256(read(codex, 'AGENTS.md')) },
    }),
  );
  expect(planProjection({ root: codex, host: 'codex', artifacts: [agents], marker: MARK }).actions).toEqual([
    { path: 'AGENTS.md', action: 'update' },
  ]);
});
it('lists every steward file it does not own as foreign and never touches it', () => {
  const root = temp(),
    unmarked = 'my own reviewer\n';
  legacy(root, { [STEWARD]: steward(HOST_MARK), '.claude/agents/listed-mine.md': unmarked });
  // Unlisted: the user's own file, and a marked one another clone or workspace left.
  put(root, '.claude/agents/x.md', unmarked);
  put(root, '.claude/agents/stray-steward.md', steward(HOST_MARK));
  const plan = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  expect(plan.actions).toEqual([
    { path: STEWARD, action: 'remove' },
    { path: '.claude/agents/listed-mine.md', action: 'foreign' },
    { path: '.claude/agents/stray-steward.md', action: 'foreign' },
    { path: '.claude/agents/x.md', action: 'foreign' },
    { path: '.claude/rules/ia-workspace.md', action: 'create' },
    { path: '.claude/skills/ia-authoring/SKILL.md', action: 'create' },
  ]);
  applyProjection(plan);
  expect(existsSync(resolve(root, STEWARD))).toBe(false);
  expect(read(root, '.claude/agents/listed-mine.md')).toBe(unmarked);
  expect(read(root, '.claude/agents/x.md')).toBe(unmarked);
  expect(read(root, '.claude/agents/stray-steward.md')).toBe(steward(HOST_MARK));
  // The state stops listing the foreign file; the next plan still lists every one, and removal leaves them too.
  expect(Object.keys(JSON.parse(read(root, STATE)).files)).toEqual(artifacts().map((artifact) => artifact.path));
  applyProjection(planProjection({ root, host: 'claude', artifacts: [], marker: MARK }));
  for (const path of ['.claude/agents/listed-mine.md', '.claude/agents/x.md', '.claude/agents/stray-steward.md'])
    expect(existsSync(resolve(root, path)), path).toBe(true);
  // A foreign file is no drift.
  expect(observeProjection({ root, host: 'claude', artifacts: null, marker: MARK })).toEqual([
    { path: '.claude/agents/stray-steward.md', drift: 'unowned' },
  ]);
});
it('refuses a listed steward file edited by hand that keeps its marker, and drops one already gone', () => {
  const root = temp();
  legacy(root, { [STEWARD]: steward(HOST_MARK) });
  put(root, STEWARD, `${steward(HOST_MARK)}edited\n`);
  expect(observeProjection({ root, host: 'claude', artifacts: null, marker: MARK })).toEqual([
    { path: STEWARD, drift: 'changed' },
  ]);
  expect(where(() => planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }))).toMatchObject({
    code: 'IA-DIST-LOCAL-MODIFICATION',
    path: STEWARD,
    message: `Managed file was edited by hand: ${STEWARD}`,
  });
  expect(read(root, STEWARD)).toBe(`${steward(HOST_MARK)}edited\n`);
  // Deleted by the user: no drift, and the apply only drops it from the state.
  rmSync(resolve(root, STEWARD));
  expect(observeProjection({ root, host: 'claude', artifacts: null, marker: MARK })).toEqual([]);
  const plan = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  expect(plan.actions[0]).toEqual({ path: STEWARD, action: 'remove' });
  applyProjection(plan);
  expect(Object.keys(JSON.parse(read(root, STATE)).files)).not.toContain(STEWARD);
});

// --- Crash safety: an interrupted apply must never look like a hand edit on the next plan/observe. ---
it('keeps an interrupted first apply from looking hand-edited and converges under different artifacts', () => {
  const root = temp(),
    plan = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  const first = plan.actions[0]!.path; // '.claude/rules/ia-workspace.md', alphabetically first, a create
  expect(() =>
    applyProjection(plan, (stage) => {
      if (stage === first) throw new Error('interrupted');
    }),
  ).toThrow('interrupted');
  expect(
    observeProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }).some(
      (d) => d.drift === 'changed',
    ),
  ).toBe(false);
  const v2 = bump(artifacts(), 'v2');
  applyProjection(planProjection({ root, host: 'claude', artifacts: v2, marker: MARK }));
  expect(observeProjection({ root, host: 'claude', artifacts: v2, marker: MARK })).toEqual([]);
});
