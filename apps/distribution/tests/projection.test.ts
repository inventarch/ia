// --- The orphan scan must be best-effort: a user's own files must never make plan/observe throw. ---
it('skips unreadable files in .claude/agents/ during the orphan scan instead of failing', () => {
  const root = temp();
  mkdirSync(resolve(root, '.claude/agents'), { recursive: true });
  writeFileSync(resolve(root, '.claude/agents/my-agent.md'), Buffer.from([0x66, 0x6f, 0x6f, 0xff, 0xfe, 0x0a])); // invalid UTF-8
  writeFileSync(resolve(root, '.claude/agents/big.md'), Buffer.alloc(1024 * 1024 + 1, 'x')); // over the 1 MiB read limit
  expect(() => planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).not.toThrow();
  expect(() => observeProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).not.toThrow();
});

// --- The pending accepted-hash set must stay bounded even under repeated interruption. ---
it('bounds the pending accepted set across several consecutive interrupted applies', () => {
  const root = temp();
  applyProjection(planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }));
  let previous = artifacts();
  for (let round = 0; round < 10; round++) {
    const next = bump(previous, `r${round}`);
    const plan = planProjection({ root, host: 'claude', artifacts: next, marker: MARK });
    const target = plan.actions.find((a) => a.action === 'update')!.path;
    expect(() =>
      applyProjection(plan, (stage) => {
        if (stage === target) throw new Error('interrupted');
      }),
    ).toThrow('interrupted');
    expect(() => observeProjection({ root, host: 'claude', artifacts: next, marker: MARK })).not.toThrow();
    previous = next;
  }
  applyProjection(planProjection({ root, host: 'claude', artifacts: previous, marker: MARK }));
  expect(observeProjection({ root, host: 'claude', artifacts: previous, marker: MARK })).toEqual([]);
});
it('resumes correctly when replanned with the same inputs after an interruption', () => {
  const root = temp(),
    plan = planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK });
  const first = plan.actions[0]!.path;
  expect(() =>
    applyProjection(plan, (stage) => {
      if (stage === first) throw new Error('interrupted');
    }),
  ).toThrow('interrupted');
  applyProjection(planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }));
  expect(observeProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual([]);
});
it('locates each refusal at the file it concerns', () => {
  const where = (run: () => unknown): { code?: string; path?: string } => {
    try {
      run();
    } catch (error) {
      return error as { code?: string; path?: string };
    }
    return {};
  };
  const root = temp();
  put(root, '.claude/rules/ia-workspace.md', 'user\n');
  expect(where(() => planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }))).toMatchObject({
    code: 'IA-DIST-LOCAL-MODIFICATION',
    path: '.claude/rules/ia-workspace.md',
  });
  const owned = temp();
  applyProjection(planProjection({ root: owned, host: 'claude', artifacts: artifacts(), marker: MARK }));
  put(owned, '.ia/distributions/hosts/claude-projection.json', '{"format":"other"}\n');
  expect(
    where(() => planProjection({ root: owned, host: 'claude', artifacts: artifacts(), marker: MARK })),
  ).toMatchObject({ code: 'IA-DIST-INPUT-INVALID', path: '.ia/distributions/hosts/claude-projection.json' });
});
it('locates each observation failure at the file it concerns', () => {
  const where = (run: () => unknown): { code?: string; path?: string } => {
    try {
      run();
    } catch (error) {
      return error as { code?: string; path?: string };
    }
    return {};
  };
  const root = temp();
  applyProjection(planProjection({ root, host: 'claude', artifacts: artifacts(), marker: MARK }));
  linkSync(resolve(root, '.claude/rules/ia-workspace.md'), resolve(root, 'alias.md'));
  expect(where(() => observeProjection({ root, host: 'claude', artifacts: null, marker: MARK }))).toMatchObject({
    code: 'IA-DIST-PATH-UNSAFE',
    path: '.claude/rules/ia-workspace.md',
  });
  rmSync(resolve(root, 'alias.md'));
  put(root, '.ia/distributions/hosts/claude-projection.json', 'garbage\n');
  expect(where(() => observeProjection({ root, host: 'claude', artifacts: null, marker: MARK }))).toMatchObject({
    path: '.ia/distributions/hosts/claude-projection.json',
  });
  const unmanaged = temp();
  applyProjection(
    planProjection({ root: unmanaged, host: 'claude', artifacts: artifacts().slice(0, 2), marker: MARK }),
  );
  put(unmanaged, 'other.md', 'x\n');
  mkdirSync(resolve(unmanaged, '.claude/agents'), { recursive: true });
  linkSync(resolve(unmanaged, 'other.md'), resolve(unmanaged, '.claude/agents/demo-steward.md'));
  expect(
    where(() => observeProjection({ root: unmanaged, host: 'claude', artifacts: artifacts(), marker: MARK })),
  ).toMatchObject({ code: 'IA-DIST-PATH-UNSAFE', path: '.claude/agents/demo-steward.md' });
});
