// --- Drift kinds beyond changed/missing/outdated. ---
it('distinguishes an unmanaged file from a marked-but-unowned one for a requested path', () => {
  const unowned = temp();
  applyProjection(planProjection({ root: unowned, host: 'claude', artifacts: [artifacts()[1]!], marker: MARK })); // owns only the skill file
  put(unowned, '.claude/rules/ia-workspace.md', 'no marker, never ours\n');
  expect(observeProjection({ root: unowned, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual(
    expect.arrayContaining([{ path: '.claude/rules/ia-workspace.md', drift: 'unmanaged' }]),
  );
  const marked = temp();
  applyProjection(planProjection({ root: marked, host: 'claude', artifacts: [artifacts()[1]!], marker: MARK }));
  put(marked, '.claude/rules/ia-workspace.md', `${MARK}\n\nsomeone else's render\n`);
  expect(observeProjection({ root: marked, host: 'claude', artifacts: artifacts(), marker: MARK })).toEqual(
    expect.arrayContaining([{ path: '.claude/rules/ia-workspace.md', drift: 'unowned' }]),
  );
});
