/**
 * The method tools against `fixtures/method`: `plugin.json.gz` holds the public `ia` plugin's scripts and support files
 * and its `ia-kb` kit (provenance in `fixtures/method/PROVENANCE.json`, regenerated by `fixtures/method/generate.mjs`), and each `golden-*.json` is the packet that
 * plugin's `resolve.mjs` printed for the same consumer, bindings, task and subject hash, with the temporary root as
 * `<ROOT>`, its digest taken over that content by the plugin's own `packetDigest`, and the envelope, which no digest
 * covers, left out. `consumer` is a workspace whose lock installs the kit through a real installation; `bare` is the same
 * workspace with no lock, which a bound kit refuses. Every kit here is the published one, its lock as shipped (it pins
 * the base the 0.9.0 release was packed on, 3.2.0), never re-locked: this door and the CLI that resolved the goldens
 * each carry that base and restore the kit on it exactly.
 */
const fixture = new URL('./fixtures/method/', import.meta.url);
const golden = (name: string): unknown => JSON.parse(readFileSync(new URL(name, fixture), 'utf8'));
const BASE = JSON.parse(readFileSync(new URL('../assets/base.json', import.meta.url), 'utf8')) as {
  id: string;
  version: string;
  archive: string;
  manifest: string;
};
let root: string, consumer: string, bare: string, kits: string, env: NodeJS.ProcessEnv;
/** The fixture's files as published: the kit's lock pins the base its release was packed on. */
let published: Record<string, string>;

beforeAll(() => {
  root = realpathSync(mkdtempSync(join(tmpdir(), 'ia-door-method-')));
  published = JSON.parse(gunzipSync(readFileSync(new URL('plugin.json.gz', fixture))).toString('utf8')) as Record<
    string,
    string
  >;
  for (const [path, text] of Object.entries(published)) {
    mkdirSync(dirname(join(root, 'plugin', path)), { recursive: true });
    writeFileSync(join(root, 'plugin', path), text);
  }
  bare = join(root, 'bare');
  mkdirSync(join(bare, '.ia', 'src'), { recursive: true });
  copyFileSync(new URL('bindings.json', fixture), join(bare, '.ia', 'bindings.json'));
  kits = join(root, 'plugin', 'config', 'kits');
  // `ia pack` of the published fixture kit, in a copy restored with the base the door chooses for its lock: the
  // archive its releases.json names.
  const source = join(root, 'packed', 'ia-kb');
  for (const [path, text] of Object.entries(published))
    if (path.startsWith('config/kits/ia-kb/')) {
      const target = join(source, path.slice('config/kits/ia-kb/'.length));
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, text);
    }
  restoreInPlace(source, folderKits(join(root, 'packed'))[0]!);
  const packed = packDistribution(source, readFileSync(join(source, '.ia', 'release.json'), 'utf8'));
  const released = readReleases(source).releases.find((row) => row.version === '0.9.0')!;
  expect([packed.archiveDigest, packed.manifestDigest]).toEqual([released.archive, released['manifest']]);
  // The same consumer, installed through the product's own plan and apply: the kit and the language base it
  // depends on as locked releases, so the lock and its active generation agree.
  consumer = join(root, 'consumer');
  mkdirSync(join(consumer, '.ia', 'src'), { recursive: true });
  copyFileSync(new URL('bindings.json', fixture), join(consumer, '.ia', 'bindings.json'));
  cacheArchive(consumer, readFileSync(new URL(`../assets/base/${BASE.archive}.ia.tgz`, import.meta.url)), BASE.archive);
  cacheArchive(consumer, packed.bytes, packed.archiveDigest);
  applyInstallation(
    planInstallation(
      consumer,
      {
        formatVersion: 1,
        engine: '^0.1.2',
        // Rows sort by id: the kit before the language base it depends on.
        requests: [
          { id: packed.manifest.id, range: `^${packed.manifest.version}` },
          { id: BASE.id, range: `^${BASE.version}` },
        ],
        packages: [
          {
            id: packed.manifest.id,
            version: packed.manifest.version,
            archive: packed.archiveDigest,
            manifest: packed.manifestDigest,
            location: `sha256:${packed.archiveDigest}`,
            dependencies: [BASE.id],
          },
          {
            id: BASE.id,
            version: BASE.version,
            archive: BASE.archive,
            manifest: BASE.manifest,
            location: `sha256:${BASE.archive}`,
            dependencies: [],
          },
        ],
      },
      'install',
    ),
  );
  env = { ...process.env, IA_HOME: join(root, 'home') };
  mkdirSync(join(root, 'cache'));
  delete env['IA_KITS_DIR'];
  delete env['IA_CORE_RUN_ROOT'];
  delete env['IA_CORE_CLOSURES_DIR'];
  delete env['IA_CORE_HOST_ENFORCES_CHECKS'];
}, 120_000);
afterAll(() => rmSync(root, { recursive: true, force: true }));

const normalized = (value: unknown): unknown => {
  if (typeof value === 'string')
    return value.includes(root) ? value.split(root).join('<ROOT>').replaceAll('\\', '/') : value;
  if (Array.isArray(value)) return value.map(normalized);
  if (value !== null && typeof value === 'object')
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, normalized(item)]));
  return value;
};
const tools = (at: string = consumer): MethodTools =>
  new MethodTools({ root: at, kits, env, cache: join(root, 'cache') });

it('refuses a bound kit the lock does not install, with the payload resolve.mjs prints, and writes nothing', () => {
  // The consumer binds knowledge.find and knowledge.check to a kit its lock does not install (it has no lock at all).
  const door = tools(bare);
  for (const activity of ['find', 'check']) {
    const answer = door.call('method:method', {
      key: `knowledge.${activity}`,
      subject: 'the decision records',
      task: 'golden',
    });
    expect(answer.ok).toBe(false);
    expect(answer.value).toEqual({
      error: {
        code: 'IA-CORE-KIT-NOT-INSTALLED',
        message:
          'kit inventarch/ia-kb-kit is bound by this repository but its lock does not install it; install the npm package that carries it with ia install --package <name> --apply --yes (the public kits ship in @inventarch/public-kits), or ia install inventarch/ia-kb-kit --apply --yes where a registry serves it, or kit.mjs add inventarch/ia-kb-kit --apply; then resolve again',
        kit: 'inventarch/ia-kb-kit',
      },
    });
  }
  expect(existsSync(join(root, 'home', 'work-v1'))).toBe(false);
  expect(existsSync(join(root, 'home', 'kit-roots-v1'))).toBe(false);
  expect(existsSync(join(root, 'home', 'method-closures-v1'))).toBe(false);
});

it('resolves the packet resolve.mjs prints, field for field, and writes the same pin', () => {
  // The lanes pass a task and no project: the pin folder's project is the workspace folder's name, the one the golden
  // run named with --project.
  expect(projectOf(consumer)).toBe('consumer');
  const door = tools();
  for (const activity of ['find', 'check']) {
    const answer = door.call('method:method', {
      key: `knowledge.${activity}`,
      subject: 'the decision records',
      task: 'golden',
    });
    // A refusal names its code: IA-CORE-CLI-MISSING when `language-base:generate` has not written assets/base.
    expect(answer.ok, JSON.stringify(answer.value)).toBe(true);
    const { envelope, ...packet } = answer.value as Record<string, unknown>;
    expect(envelope).toMatchObject({ host: 'mcp-door', cliSource: 'in-process', kitInstalled: true });
    expect(packet['digest']).toBe(packetDigest(packet));
    // The digest covers the workspace root, so each side's is compared over the same `<ROOT>` content.
    const same = normalized(packet) as Record<string, unknown>;
    expect({ ...same, digest: packetDigest(same) }).toEqual(golden(`golden-${activity}.json`));
  }
  const { createdAt, ...pin } = JSON.parse(
    readFileSync(join(root, 'home', 'work-v1', 'consumer', 'golden', 'binding.json'), 'utf8'),
  ) as Record<string, unknown>;
  expect(typeof createdAt).toBe('string');
  expect(normalized(pin)).toEqual(golden('golden-pin.json'));
}, 120_000);

