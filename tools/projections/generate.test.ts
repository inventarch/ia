const put = (base: string, path: string, text: string): void => {
  mkdirSync(dirname(resolve(base, path)), { recursive: true });
  writeFileSync(resolve(base, path), text);
};
const read = (base: string, path: string): string => readFileSync(resolve(base, path), 'utf8');
/** A copy of this repository's native corpus, the layout the generator reads, with no projection file yet. */
function copy(): string {
  const base = temp();
  cpSync(resolve(root, '.ia/src'), resolve(base, '.ia/src'), { recursive: true });
  return base;
}
/**
 * A steward-guard registration as a 1.x `ia host` wrote it over an existing `settings` file: the group
 * guard-registration derives for this root appended to its PreToolUse array in place, and the ownership state its
 * planner records, the containers that were already there kept as `existing`. A removal never reads the cache.
 */
function registerGuard(base: string, settings: string): string {
  const real = realpathSync(base),
    cache = temp(),
    group = guardGroup(join(cache, 'scripts/ia.mjs'), real),
    existing = presentJson(settings, [['hooks'], ['hooks', 'PreToolUse']]);
  const text = editJson(settings, ['hooks', 'PreToolUse', -1], group, existing);
  put(base, GUARD_SETTINGS, text);
  put(
    base,
    GUARD_STATE,
    json({
      format: 'ia.guard-registration-state.v1',
      id: 'workspace',
      cache,
      release: 'a'.repeat(64),
      created: false,
      group,
      ...(existing.length === 0 ? {} : { existing }),
    }),
  );
  return text;
}
/** A token GitHub would render as a mention: a bare `@<word>` outside every code span. */
const bare = (text: string): readonly string[] =>
  text.replace(/(`+)[\s\S]*?(?<!`)\1(?!`)/g, '').match(/(?<![\w.\-/@`])@[a-z][a-z0-9-]*(?![\w\-/@])/g) ?? [];

it('renders this repository as its position packet: CLAUDE.md and both skills, no steward agent, as committed', () => {
  const files = renderProjections(root);
  expect(files.map((file) => file.path)).toEqual(FILES);
  for (const file of files) {
    expect(file.text.split('\n'), file.path).toContain(PACKET_MARKER);
    expect(file.text, file.path).toBe(read(root, file.path));
  }
  const claude = files[0]!.text;
  expect(claude.startsWith(`${PACKET_MARKER}\n\n# IA position packet: language-workspace\n`)).toBe(true);
  // One participant entry (plan task self-host-participant-records), and no host note in a committed file.
  const participants = claude.split('## Participants\n\n')[1]!.split('\n\n')[0]!.split('\n');
  expect(participants).toEqual([
    '- `agent-system/binding/agent/language-participant`: The IDE agent operating in the language workspace, any vendor.',
  ]);
  expect(claude).not.toContain('Host note');
  // Plan amendment B1 with the milestone's final catalog (C = 7, task ia-project-verb): 1 participant, 1 mandate, the
  // seat, 11 system lines, 22 tallies, 5 intent rows, 4 phase rows, 7 commands, provenance and 3 SPEC lines. The file
  // renders one entry per list item and table row, and the provenance line.
  const db = open(root, { cache: false });
  try {
    const { packet } = renderPacket(db, db.resolveScope().token, packetCatalog());
    expect(
      [packet.participants, packet.mandates, packet.systems, packet.tallies, packet.commands].map(
        (rows) => rows.length,
      ),
    ).toEqual([1, 1, 11, 22, 7]);
    expect(entryCount(packet)).toBe(56);
  } finally {
    db.close();
  }
  const lines = claude.split('\n'),
    rows = lines.filter(
      (line, index) => line.startsWith('| ') && !line.startsWith('| ---') && !lines[index + 1]?.startsWith('| ---'),
    );
  expect(lines.filter((line) => line.startsWith('- ') || line.startsWith('ia-generated ')).length + rows.length).toBe(
    56,
  );
  expect(rows).toContain(
    '| `ia project` | effect | Execution | a file without the generated marker at a path it writes, which its plan names; --apply writes nothing | `ia project <host>` |',
  );
  expect(rows).toContain(
    '| `ia capture` | effect | Execution | an uninitialized root with no authored `@workspace` and no source errors; nothing is written | `ia init <directory>` |',
  );
  // GitHub renders the committed file: every IA word in it is a code span, never a mention.
  expect(claude).toContain('`@workspace`');
  expect(bare(claude)).toEqual([]);
  // The tree holds no marked steward agent and no guard registration: the check finds nothing to do.
  expect(generateProjections(root, false)).toEqual([]);
  const base = temp();
  expect(publishArtifacts(base, files, false)).toEqual(FILES);
  publishArtifacts(base, files, true);
  expect(publishArtifacts(base, files, false)).toEqual([]);
});
it('commits CLAUDE.md and both skills, and ignores .claude/agents, where no file is tracked (packet-tracking-policy)', () => {
  // Milestone position-packet task untrack-steward-agents: no steward agent is tracked, and none can be added unforced.
  const base = temp(),
    empty = resolve(base, 'empty'),
    scratch = resolve(base, 'repository'),
    agent = '.claude/agents/public-work-system-steward.md';
  writeFileSync(empty, '');
  const git = (cwd: string, env: NodeJS.ProcessEnv, ...args: string[]): string[] => {
    const run = spawnSync('git', args, { cwd, encoding: 'utf8', timeout: 15000, env });
    expect(run.status, run.stderr).toBe(0);
    return run.stdout.split('\n').filter(Boolean);
  };
  // This checkout's index is read with the contributor's own Git environment: ls-files reads no ignore rule, and Git
  // honours a safe.directory only from system, global or command configuration.
  const tracked = (...paths: string[]): string[] => git(root, process.env, 'ls-files', '--', ...paths);
  expect(tracked(...FILES, '.claude/agents').sort()).toEqual([...FILES].sort());
  // The ignore check runs in a repository made without a template, so without an info/exclude, holding copies of the
  // tracked ignore files. Its Git has no inherited GIT_* variable, no system or global configuration and an empty
  // excludes file, so a contributor's own ignore rules can neither hide a tracked file nor stand in for the tracked
  // rule. --no-index matches each path, tracked or not, and -v names the rule behind each ignored path.
  const isolated = {
    ...Object.fromEntries(Object.entries(process.env).filter(([name]) => !name.startsWith('GIT_'))),
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_CONFIG_GLOBAL: empty,
  };
  const ignores = (cwd: string, ...args: string[]): string[] =>
    git(cwd, isolated, '-c', `core.excludesFile=${empty}`, ...args);
  ignores(base, 'init', '--quiet', '--template=', scratch);
  for (const path of tracked(':(glob)**/.gitignore')) put(scratch, path, read(root, path));
  const rule = read(root, '.gitignore').split(/\r?\n/).indexOf('/.claude/agents/') + 1;
  expect(rule).toBeGreaterThan(0);
  expect(ignores(scratch, 'check-ignore', '-v', '--no-index', '--', ...FILES, agent)).toEqual([
    `.gitignore:${rule}:/.claude/agents/\t${agent}`,
  ]);
});
