it('retires the guard before the first stale-agent unlink fails, and resumes without losing foreign files', async () => {
  const base = temp(),
    permissions = '{\n  "permissions": {"allow": ["Read"]},\n  "hooks": {"PreToolUse": []}\n}\n',
    foreign = '.claude/agents/my-reviewer.md',
    files = [{ path: 'CLAUDE.md', text: `${PACKET_MARKER}\n` }];
  put(base, LEGACY_AGENT, LEGACY_TEXT);
  put(base, foreign, LEGACY_TEXT);
  registerGuard(base, permissions);
  const actual = await vi.importActual<typeof import('node:fs')>('node:fs'),
    failure = Object.assign(new Error('injected locked stale agent'), {
      code: 'EPERM',
      path: resolve(base, LEGACY_AGENT),
    }),
    attempts: string[] = [];
  vi.mocked(unlinkSync).mockImplementation((target) => {
    if (String(target) === resolve(base, LEGACY_AGENT)) {
      attempts.push(String(target));
      throw failure;
    }
    actual.unlinkSync(target);
  });
  try {
    expect(() => publishArtifacts(base, files, true)).toThrow(failure);
    expect(attempts).toEqual([resolve(base, LEGACY_AGENT)]);
    // This is observed after the FIRST attempted agent unlink, before any packet publication or retry.
    // Moving applyGuardRegistration below the stale loop leaves both guard assertions failing.
    expect(existsSync(resolve(base, GUARD_STATE))).toBe(false);
    expect(read(base, GUARD_SETTINGS)).toBe(permissions);
    expect(read(base, LEGACY_AGENT)).toBe(LEGACY_TEXT);
    expect(read(base, foreign)).toBe(LEGACY_TEXT);
    expect(existsSync(resolve(base, 'CLAUDE.md'))).toBe(false);
  } finally {
    vi.mocked(unlinkSync).mockImplementation(actual.unlinkSync);
  }
  expect(publishArtifacts(base, files, true)).toEqual([LEGACY_AGENT, 'CLAUDE.md']);
  expect(read(base, foreign)).toBe(LEGACY_TEXT);
  expect(publishArtifacts(base, files, false)).toEqual([]);
});
